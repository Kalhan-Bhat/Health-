"""Tests for PDF validation and text extraction (spec §8.3, §14.2).

Uses only the synthetic PDFs generated by scripts/make_sample_pdfs.py.
"""

from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from app.errors import AppError
from app.main import app
from app.services.pdf_extractor import normalize_text, validate_and_extract

FIXTURES = Path(__file__).parent / "fixtures"


def _load(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


def _extract(name: str):
    return validate_and_extract(_load(name), name, "application/pdf")


# --------------------------------------------------------------- good PDFs


@pytest.mark.parametrize(
    "name, expected_strings",
    [
        ("sample_cbc_low_hb.pdf", ["Haemoglobin", "10.8", "12.0 - 15.5", "2,45,000"]),
        ("sample_lipid_high_ldl.pdf", ["LDL Cholesterol", "162", "Triglycerides", "< 150"]),
        ("sample_thyroid_metabolic_mixed.pdf", ["TSH", "HbA1c", "Potassium", "CRITICAL"]),
    ],
)
def test_good_pdfs_extract_known_text(name: str, expected_strings: list[str]) -> None:
    result = _extract(name)
    assert result.pages == 1
    assert result.method in ("pymupdf", "pdfplumber")
    for s in expected_strings:
        assert s in result.text, f"{s!r} missing from extracted text of {name}"


def test_table_rows_keep_reading_order() -> None:
    # The value should appear on the same line as its test name (table layout preserved).
    text = _extract("sample_cbc_low_hb.pdf").text
    hb_line = next(line for line in text.splitlines() if "Haemoglobin" in line)
    assert "10.8" in hb_line


# --------------------------------------------------------------- error cases


@pytest.mark.parametrize(
    "name, code",
    [
        ("scanned_like.pdf", "SCANNED_PDF_UNSUPPORTED"),
        ("encrypted.pdf", "ENCRYPTED_PDF"),
        ("too_many_pages.pdf", "TOO_MANY_PAGES"),
    ],
)
def test_bad_pdfs_raise_correct_code(name: str, code: str) -> None:
    with pytest.raises(AppError) as exc_info:
        _extract(name)
    assert exc_info.value.code == code
    assert exc_info.value.status_code == 422


def test_non_pdf_bytes_rejected() -> None:
    with pytest.raises(AppError) as exc_info:
        validate_and_extract(b"hello, I am a text file", "report.pdf", "application/pdf")
    assert exc_info.value.code == "UNSUPPORTED_FILE_TYPE"


def test_wrong_extension_rejected() -> None:
    with pytest.raises(AppError) as exc_info:
        validate_and_extract(_load("sample_cbc_low_hb.pdf"), "report.txt", "application/pdf")
    assert exc_info.value.code == "UNSUPPORTED_FILE_TYPE"


def test_normalize_text_collapses_blank_lines_and_nulls() -> None:
    assert normalize_text("a\x00b\n\n\n\n\nc      d") == "ab\n\nc  d"


# --------------------------------------------------------------- via the endpoint

client = TestClient(app)


def _post(name: str, data: bytes, mime: str = "application/pdf"):
    return client.post("/api/analyze-report", files={"file": (name, data, mime)})


def _assert_error(res, status: int, code: str) -> None:
    assert res.status_code == status, res.text
    body = res.json()
    assert set(body) == {"error"}
    assert body["error"]["code"] == code
    assert isinstance(body["error"]["message"], str) and body["error"]["message"]
    assert isinstance(body["error"]["details"], dict)


def test_endpoint_missing_file() -> None:
    _assert_error(client.post("/api/analyze-report", data={}), 400, "NO_FILE")


def test_endpoint_non_pdf() -> None:
    _assert_error(_post("notes.txt", b"plain text", "text/plain"), 415, "UNSUPPORTED_FILE_TYPE")


def test_endpoint_scanned() -> None:
    _assert_error(_post("scan.pdf", _load("scanned_like.pdf")), 422, "SCANNED_PDF_UNSUPPORTED")


def test_endpoint_encrypted() -> None:
    _assert_error(_post("locked.pdf", _load("encrypted.pdf")), 422, "ENCRYPTED_PDF")


def test_endpoint_too_many_pages() -> None:
    _assert_error(_post("long.pdf", _load("too_many_pages.pdf")), 422, "TOO_MANY_PAGES")


def test_endpoint_oversize(monkeypatch: pytest.MonkeyPatch) -> None:
    # 11 MB of data that starts like a PDF; rejected while reading, before parsing.
    big = b"%PDF-1.4\n" + b"0" * (11 * 1024 * 1024)
    _assert_error(_post("big.pdf", big), 413, "FILE_TOO_LARGE")
